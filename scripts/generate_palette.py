#!/usr/bin/env python3
"""Generate the shared QML palette in OKLab; --check reads the committed qrc header in CI."""

import argparse
import math
import pathlib
import subprocess
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
REL = pathlib.Path("qml/commons/YColors.qml")
HUES = {
    "azure": 250,
    "teal": 190,
    "greenFamily": 150,
    "amber": 65,
    "rose": 25,
    "violet": 300,
}
NEUTRAL = [
    "0D0E14",
    "1A1B21",
    "2C2D34",
    "46474E",
    "676870",
    "90929A",
    "B5B7BF",
    "D2D4DC",
    "EBECF2",
]
STEPS = {
    "tint": (1.28, 0.30),
    "surface": (1.62, 0.42),
    "line": (2.45, 0.62),
    "solid": (3.60, 0.74),
    "hover": (4.60, 0.74),
    "text": (7.60, 0.50),
}


def linear(l, c, hue):
    a, b = c * math.cos(math.radians(hue)), c * math.sin(math.radians(hue))
    x, y, z = (
        (l + 0.3963377774 * a + 0.2158037573 * b) ** 3,
        (l - 0.1055613458 * a - 0.0638541728 * b) ** 3,
        (l - 0.0894841775 * a - 1.291485548 * b) ** 3,
    )
    return (
        4.0767416621 * x - 3.3077115913 * y + 0.2309699292 * z,
        -1.2684380046 * x + 2.6097574011 * y - 0.3413193965 * z,
        -0.0041960863 * x - 0.7034186147 * y + 1.707614701 * z,
    )


def channel(v):
    return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4


def luminance(color):
    rgb = [channel(int(color[i : i + 2], 16) / 255) for i in (1, 3, 5)]
    return sum(v * w for v, w in zip(rgb, (0.2126, 0.7152, 0.0722)))


def contrast(a, b):
    x, y = sorted((luminance(a), luminance(b)))
    return (y + 0.05) / (x + 0.05)


def swatch(hue, target, fraction):
    lo, hi = 0.0, 1.0
    for _ in range(40):
        l = (lo + hi) / 2
        c0, c1 = 0.0, 0.5
        for _ in range(30):
            c = (c0 + c1) / 2
            if all(0 <= v <= 1 for v in linear(l, c, hue)):
                c0 = c
            else:
                c1 = c
        rgb = linear(l, c0 * fraction, hue)
        lum = sum(v * w for v, w in zip(rgb, (0.2126, 0.7152, 0.0722)))
        if (lum + 0.05) / (luminance("#1A1B21") + 0.05) < target:
            lo = l
        else:
            hi = l

    def encode(v):
        return round(
            255 * (12.92 * v if v <= 0.0031308 else 1.055 * v ** (1 / 2.4) - 0.055)
        )

    return "#" + "".join(f"{encode(v):02X}" for v in rgb)


def lightness(color):
    r, g, b = [channel(int(color[i : i + 2], 16) / 255) for i in (1, 3, 5)]
    l = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b) ** (1 / 3)
    m = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b) ** (1 / 3)
    s = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b) ** (1 / 3)
    return 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s


def generate():
    families = {
        name: {step: swatch(hue, *params) for step, params in STEPS.items()}
        for name, hue in HUES.items()
    }
    for step in STEPS:
        levels = [lightness(colors[step]) for colors in families.values()]
        assert max(levels) - min(levels) <= 0.05
    for colors in families.values():
        for step, (target, _) in STEPS.items():
            assert abs(contrast(colors[step], "#1A1B21") - target) < 0.06
        assert contrast("#FFFFFF", colors["solid"]) >= 4.5
        assert contrast(colors["text"], colors["surface"]) >= 4.5
    lines = [
        "pragma Singleton",
        "",
        "import QtQuick 2.12",
        "",
        "// Generated by scripts/generate_palette.py. Do not edit by hand.",
        "QtObject {",
        "    readonly property QtObject neutral: QtObject {",
    ]
    lines += [
        f'        readonly property color n{900-i*100}: "#{c}"'
        for i, c in enumerate(NEUTRAL)
    ]
    lines += ["    }"]
    for name, colors in families.items():
        lines += [f"    readonly property QtObject {name}: QtObject {{"]
        lines += [
            f'        readonly property color {step}: "{color}"'
            for step, color in colors.items()
        ]
        lines += ["    }"]
    aliases = {
        "bg": "neutral.n900",
        "surface": "neutral.n800",
        "textPrimary": "neutral.n200",
        "textSecondary": "neutral.n400",
        "border": "neutral.n700",
        "accent": "azure.solid",
        "success": "greenFamily.solid",
        "warning": "amber.solid",
        "danger": "rose.solid",
        "info": "azure.solid",
        "onSolid": '"#FFFFFF"',
        "black": "bg",
        "white": "onSolid",
        "red": "danger",
        "orange": "amber.hover",
        "green": "success",
        "yellow": "warning",
        "blueText": "azure.text",
        "blueRect": "accent",
        "grayText": "textSecondary",
        "grayNormal": "surface",
        "graySwitchOff": "neutral.n600",
        "grayButton": "neutral.n700",
    }
    lines += [
        f"    readonly property color {name}: {value}"
        for name, value in aliases.items()
    ]
    lines += [
        "    readonly property Gradient redDict: Gradient {",
        "        GradientStop { position: 0.0; color: YColors.rose.hover }",
        "        GradientStop { position: 1.0; color: YColors.rose.solid }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        with tempfile.TemporaryDirectory() as tmp:
            subprocess.run(
                [
                    "python3",
                    str(ROOT / "scripts/unpack_qrc.py"),
                    "-p",
                    "YDP02X",
                    "-o",
                    tmp,
                ],
                check=True,
                stdout=subprocess.DEVNULL,
            )
            actual = (pathlib.Path(tmp) / REL).read_text()
        if actual != expected:
            raise SystemExit(
                "Palette differs from generator; regenerate YColors.qml and qrc_qml.h"
            )
        print(
            "Palette matches committed resource; all six families pass contrast checks."
        )
    else:
        (ROOT / "resource/models/YDP02X" / REL).write_text(expected)
        print("Generated YColors.qml; regenerate qrc_qml.h before committing.")


if __name__ == "__main__":
    main()
